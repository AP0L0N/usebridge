export type WsStrKey = keyof typeof S;

export function t(key: WsStrKey, vars: Record<string, string | number> = {}): string {
  return S[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** "1 ticket" / "3 tickets" style plurals from a one/many key pair. */
export function tn(n: number, one: WsStrKey, many: WsStrKey): string {
  return t(n === 1 ? one : many, { n });
}
