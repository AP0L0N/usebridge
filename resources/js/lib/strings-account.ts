export type AcctKey = keyof typeof SA;

export function t(key: AcctKey, vars: Record<string, string | number> = {}): string {
  return SA[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** "1 project" / "3 projects" from a .one / .many key pair. */
export function tn(base: 'acct.count.project' | 'acct.count.ticket' | 'acct.count.token' | 'acct.sess' | 'acct.sess.ended' | 'tok.expiresIn', n: number): string {
  return t(`${base}.${n === 1 ? 'one' : 'many'}` as AcctKey, { n });
}
